def _パス(種別: str) -> str:
    return os.path.join(_CONFIG_DIR, _ファイル定義[種別]["ファイル名"])


def _context_template_payload(種別: str) -> dict:
    定義 = _ファイル定義[種別]
    payload = {"version": 1, "description": 定義["説明"]}
    payload.update({キー: list(行) for キー, 行 in 定義["ひな形"].items()})
    return payload


def _compose_instruction(lines: list) -> str:
    text = "\n".join(str(行) for 行 in lines)
    if not text.endswith("\n"):
        text += "\n"
    return text


def _ひな形書き出し(種別: str, 理由: str) -> dict:
    payload = _context_template_payload(種別)
    パス = _パス(種別)
    try:
        os.makedirs(_CONFIG_DIR, exist_ok=True)
        with open(パス, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2, ensure_ascii=False)
        print(f"[Team] 定型コンテキストJSONを{理由}: {パス}", flush=True)
    except Exception as e:
        print(f"[Team] 定型コンテキストJSON書き出しエラー: {e}", flush=True)
    return payload


def _load_or_create(種別: str) -> dict:
    """定型コンテキストJSONを読み込む。無ければひな形を作成して返す。

    キー単位で検証し、欠けているキー・形式不正なキーだけひな形で補う。
    JSON 自体が壊れているときはファイルを上書きせず、既定値で動かす。
    """
    パス = _パス(種別)
    if not os.path.exists(パス):
        return _ひな形書き出し(種別, "作成")

    try:
        with open(パス, "r", encoding="utf-8-sig") as f:
            payload = json.load(f)
    except Exception as e:
        print(f"[Team] 定型コンテキスト読込エラー: {パス} {e}", flush=True)
        return _context_template_payload(種別)

    if not isinstance(payload, dict):
        return _ひな形書き出し(種別, "形式不正のため再作成")

    結果 = dict(payload)
    for キー, ひな形 in _ファイル定義[種別]["ひな形"].items():
        if not isinstance(payload.get(キー), list):
            print(f"[Team] 定型コンテキストのキー '{キー}' が不正。ひな形を使います: {パス}", flush=True)
            結果[キー] = list(ひな形)
    return 結果


_キャッシュ: dict = {}


def コンテキスト取得(種別: str, キー: str) -> str:
    """指定キーの定型コンテキストを 1 本のテキストとして返す（プロセス内で1回だけ読込）"""
    if 種別 not in _キャッシュ:
        _キャッシュ[種別] = _load_or_create(種別)
    行 = _キャッシュ[種別].get(キー)
    if not isinstance(行, list):
        行 = _ファイル定義[種別]["ひな形"].get(キー, [])
    return _compose_instruction(行)


def 差し込み(種別: str, キー: str, 値: dict) -> str:
    """定型コンテキストの `{名前}` を値で置換して返す。

    値に無いキーはそのまま残し、差し込んだ値の中身は再走査しない。
    """
    テキスト = コンテキスト取得(種別, キー)

    def _置換(m):
        名前 = m.group(1)
        return str(値[名前]) if 名前 in 値 else m.group(0)

    return _差込パターン.sub(_置換, テキスト)
