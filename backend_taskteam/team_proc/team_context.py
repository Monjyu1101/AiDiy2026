"""AIチームの定型コンテキスト読込。

`_config/AiDiy_team__<種別>_context.json` が無ければひな形を書き出し、あればその内容を使う。
task 側の `task_sub/sub_context.py` と同じ方式で、標準ライブラリのみで動作する。
用途ごとにファイルを分けてあるので、調整したい部分のファイルだけを開けばよい。

  spdca  : 作業ループ SPDCA（S=相談 / P=計画 / D=実行 / C=評価 / A=改善）
  plando : 作業ループ PlanDo（P=計画 / D=実行）
  select : 依頼を担当させる要員の選択
  exp    : 完了した依頼から経験値をまとめる
  talk   : 要員の自律発言（雑談）と admin の作業取りまとめ
  chat   : 要員チャットのペルソナ指示

作業ループ（spdca / plando）は外枠を共通化し、
`[プロジェクト]` → `[チーム目標]` → `[チーム作業]` → `[引き継ぎ]` → `[今回要求]` の順に並べる。
段ごとに変わる役割と指示は `[今回要求]` 側へ置くので、同じループの中では先頭が変わらない。

各テンプレートは `{名前}` 形式の差込キーを含む。差し込みは 1 回だけの走査で行うため、
プロンプト中の JSON の例はエスケープ不要で、差し込んだ値の中身は再走査されない。
"""

