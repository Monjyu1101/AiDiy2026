for scene_id, update in UPDATES.items():
    heading = f"### {scene_id} — {update['title']}"
    match = re.search(rf"(?ms)^### {scene_id} — [^\n]+\n.*?(?=^### scene_|\Z)", before)
    if not match:
        raise RuntimeError(f"構成欄の見出しが不一致: {scene_id}")
    section = match.group()
    section = re.sub(rf"^### {scene_id} — [^\n]+", heading, section, count=1)
    for label, value in (("一言", update["short"]), ("詳説ナレーション案", update["long"]), ("聞き流し用原稿", update["long"])):
        section, count = re.subn(rf"(?m)^\*\*{label}\*\*：[^\n]*$", lambda _: f"**{label}**：{value}", section)
        if count != 1:
            raise RuntimeError(f"構成欄の{label}が不一致: {scene_id} {count}")
    before = before[:match.start()] + section + before[match.end():]
    pattern = rf"(?ms)(^### {scene_id} — [^\n]+\n(?:\*\*間合い\*\*[^\n]+\n)?\n)(.*?)(?=\n### scene_|\Z)"
    match = re.search(pattern, after)
    if not match:
        raise RuntimeError(f"ロング版原稿が見つかりません: {scene_id}")
    start, end = match.span()
    prefix = re.sub(rf"^### {scene_id} — [^\n]+", heading, match.group(1), count=1)
    after = after[:start] + prefix + update["long"] + "\n" + after[end:]
