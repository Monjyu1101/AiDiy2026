"""作業ループ（S → P → D → C → A）の C（評価）を投入するサブプロセス。

直前のD（実行）が全件「済」または「エラー」になった後、Dの「済」レコードに保存された
まとめ内容（実施報告）を受け取り、実施内容が正しいかを実物に当たって検査させる。
実施報告だけでは何を狙った変更か分からないため、同ループのP（計画）のまとめも一緒に渡す。
検査のための読み取り・確認コマンドは実行してよいが、ソースの修正は行わせない。

team_watcher.py（1分ごとの確認）が temp/pdca/<ファイル名>.json に入力値を書き、
このスクリプトを `python sub_SPDCA_check.py <入力JSONパス>` で起動する。

前段の確認・担当要員のAI選択は `sub_SPDCA__common.py`（D・C・A 共通）が行う。
ここではAIへ渡すプロンプトだけを定義する。C は調査・検査だけでソースを変更しないため、
aidiy_task_agents（backend_task）は経由せず、sub_self_talk.py と同じ経路で
aidiy_code_agents を直接呼び出してその場で完了させる（段を実行 の 直接実行=True）。
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import sub_SPDCA__common


def プロンプト生成_評価(
    要員ID: str,
    プロジェクト: str,
    チーム目標: str,
    チーム作業: str,
    まとめ一覧: dict,
) -> str:
    計画節 = sub_SPDCA__common.参照節("P（計画）で決まった実行計画", まとめ一覧.get("P", ""))
    実施本文 = まとめ一覧.get("D", "")
    return f"""AIチーム作業のC（評価）として、D（実行）で実施された内容を検査してください。

担当要員: {要員ID}
プロジェクト: {プロジェクト}
チーム目標: {チーム目標}
チーム作業: {チーム作業}

{計画節}
## D（実行）の実施報告

{実施本文}

## 検査の進め方

報告を読むだけで判断せず、必ず実物（コード・設定・ドキュメント）に当たって確認してください。

- 報告に挙がっている変更が、実際にその内容で入っているかを確認する
- 計画（P）の各ステップが完了条件を満たしているか、着手されていないステップが無いかを確認する
- 変更が目的（チーム作業と計画の狙い）を満たしているかを確認する
- 抜け漏れ、書き換え漏れ、既存機能への副作用、不整合が無いかを確認する
- 型チェック・テスト・ビルドなど、状態を変えずに確認できる手段があれば実行して結果を見る
- 報告に書かれていない変更が入っていないかも確認する

## 厳守事項: この段は検査だけを行うこと

ここは評価（C）の段です。実行（D）は終わっており、直しは次のA（改善）以降で扱います。
ファイル読み取り、検索、ログ確認、テスト実行など**状態を変えない確認は自由に行ってよい**が、
次の操作は理由を問わず**一切行わないこと**。

- ソースコード・設定ファイル・ドキュメントの作成、編集、削除、リネーム
- インストール、デプロイ、データやDBを書き換えるコマンドの実行
- git のコミット、プッシュ、ブランチ操作

「小さな修正だから」「ついでに直せるから」という判断も不可です。
直すべきと判断した内容は、実施せずに指摘として文章で書いてください。

## 報告内容

検査後、次を簡潔にまとめて回答してください。

- 検査した観点ごとの判定（問題なし / 要修正 / 判断不能）と、その根拠（確認したファイルや実行結果）
- 見つかった問題点。重要度と、影響する範囲を添える
- 実施内容がチーム作業に対してどれだけ前進したかの評価
- 次のA（改善）で確認・改善すべき点
"""


def main() -> int:
    return sub_SPDCA__common.段を実行(
        "C", "D", プロンプト生成_評価, "sub_SPDCA_check", 参照区分=("P",), 直接実行=True
    )


if __name__ == "__main__":
    raise SystemExit(main())
