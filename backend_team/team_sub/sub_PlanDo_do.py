"""作業ループ（P → D）の D（実行）を投入するサブプロセス。

直前のP（計画）が全件「済」または「エラー」になった後、Pの「済」レコードに保存された
まとめ内容（実行計画）を実際に実施させる。Pと違い、この段はソースやドキュメントを
変更してよい段。担当は新たにAIへ選ばせず、計画を立てた本人（Pの担当要員）がそのまま実施する。

このサイクルはP（チーム作業 + 前ループDのまとめ）→ D（チーム作業 + 同ループPのまとめ）の
2段だけで、いずれも受け取るまとめ内容は1件。過去ループぶんを積み上げないため、
ループ回数を増やしてもAIへ渡すコンテキストは一定に保たれる。

team_watcher.py（1分ごとの確認）が temp/pdca/<ファイル名>.json に入力値を書き、
このスクリプトを `python sub_PlanDo_do.py <入力JSONパス>` で起動する。

前段の確認・依頼/作業レコードの作成・タスク投入は
`sub_SPDCA__common.py`（D・C・A 共通）が行う。ここではAIへ渡すプロンプトだけを定義する。
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import sub_SPDCA__common


def プロンプト生成_実行(
    要員ID: str,
    プロジェクト: str,
    チーム作業: str,
    まとめ一覧: dict,
) -> str:
    計画本文 = まとめ一覧.get("P", "")
    return f"""AIチーム作業のD（実行）として、P（計画）で決まった内容を実際に実施してください。

担当要員: {要員ID}
プロジェクト: {プロジェクト}
チーム作業: {チーム作業}

## P（計画）で決まった実行計画

{計画本文}

## 進め方

- 計画のステップを順に実施し、各ステップの完了条件を満たすまで進める
- 着手前に対象の現状（コード・ドキュメント・設定）を確認し、計画との差異があれば実態に合わせる
- 変更したら、その範囲で動作確認（型チェック、テスト、起動確認など可能なもの）を行う
- 計画どおりに実施できなかったステップは、理由と現状を残す

## この段は変更してよい段です

P（計画）では調査だけでしたが、ここは実行の段です。
計画に沿ったソースコード・設定・ドキュメントの変更を実際に行ってください。

ただし次は守ってください。

- 計画に無い変更を広げないこと。必要だと気づいた追加依頼は、実施せず報告に書く
- 動作している既存機能を壊さないこと。影響範囲を確認してから変更する
- git のコミット、プッシュ、ブランチ操作は行わないこと（変更は依頼ツリーに残すだけにする）
- 破壊的な操作（データベースやファイルの一括削除、環境の初期化など）は行わないこと

## 報告内容

実施後、次を簡潔にまとめて回答してください。

- 実施したステップと、変更したファイル・内容
- 動作確認の方法と結果（実行できなかった場合はその理由）
- 実施できなかったステップと理由
- 次サイクルのP（計画）へ引き継ぐべき観点、気づいた残課題（このサイクルにはC・A・Sが無いため、
  ここで書いた内容がそのまま次のP（計画）の前提として渡されます）
"""


def main() -> int:
    return sub_SPDCA__common.段を実行("D", "P", プロンプト生成_実行, "sub_PlanDo_do", 要員継続=True)


if __name__ == "__main__":
    raise SystemExit(main())
