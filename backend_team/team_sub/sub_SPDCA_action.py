"""作業ループ（S → P → D → C → A）の A（改善）を投入するサブプロセス。

直前のC（評価）が全件「済」または「エラー」になった後、Cの「済」レコードに保存された
まとめ内容（検査結果）を受け取り、実際に動かして改善点が無いかを確認させる。
ここは1周の締めくくりで、次サイクルへの申し送りを作る段のため、同ループの
P（計画）とD（実行）のまとめも一緒に渡し、1周ぶんの経緯を見て判断させる。
動作確認のための実行は行ってよいが、ソースの修正は行わせない。
ここでまとめた改善点は、次サイクルのS（相談）へ引き継がれて改善が続いていく。
担当は新たにAIへ選ばせず、検査を行った本人（Cの担当要員）がそのまま実施する（要員継続）。

team_watcher.py（1分ごとの確認）が temp/pdca/<ファイル名>.json に入力値を書き、
このスクリプトを `python sub_SPDCA_action.py <入力JSONパス>` で起動する。

前段の確認・担当要員の引き継ぎは `sub_SPDCA__common.py`（D・C・A 共通）が行う。
ここではAIへ渡すプロンプトだけを定義する。A は動作確認と改善点の洗い出しだけで
ソースを変更しないため、aidiy_task_agents（backend_task）は経由せず、sub_self_talk.py
と同じ経路で aidiy_code_agents を直接呼び出してその場で完了させる（段を実行 の 直接実行=True）。
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import sub_SPDCA__common


def プロンプト生成_改善(
    要員ID: str,
    プロジェクト: str,
    チーム目標: str,
    チーム作業: str,
    まとめ一覧: dict,
) -> str:
    計画節 = sub_SPDCA__common.参照節("P（計画）で決まった実行計画", まとめ一覧.get("P", ""))
    実施節 = sub_SPDCA__common.参照節("D（実行）の実施報告", まとめ一覧.get("D", ""))
    評価本文 = まとめ一覧.get("C", "")
    return f"""AIチーム作業のA（改善）として、実際に動作させたうえで改善点を洗い出してください。

担当要員: {要員ID}
プロジェクト: {プロジェクト}
チーム目標: {チーム目標}
チーム作業: {チーム作業}

{計画節}
{実施節}
## C（評価）の検査結果

{評価本文}

## 進め方

このサイクルの計画（P）・実施報告（D）・検査結果（C）を踏まえ、
実際に動かして確かめたうえで改善点をまとめてください。

- 対象の機能を実際に動作させる（起動、コマンド実行、テスト実行、画面や API の応答確認など）
- 動かした結果と、計画で狙った状態・検査結果・チーム作業の期待とのズレを確認する
- 使い勝手、性能、エラー時の挙動、分かりにくい箇所など、動かして初めて分かる点を拾う
- Cで「要修正」とされた点が実際にどう影響しているかを、動作で確かめる
- 動作させられない場合は、その理由と代わりに行った確認方法を残す

## 厳守事項: この段は動作確認と改善点の洗い出しだけを行うこと

ここは改善（A）の段で、直しの実施は次サイクルのD（実行）で行います。
動作させるためのコマンド実行、テスト実行、ログ確認は**自由に行ってよい**が、
次の操作は理由を問わず**一切行わないこと**。

- ソースコード・設定ファイル・ドキュメントの作成、編集、削除、リネーム
- git のコミット、プッシュ、ブランチ操作
- 破壊的な操作（データベースやファイルの一括削除、環境の初期化など）

「小さな修正だから」「ついでに直せるから」という判断も不可です。
直すべき内容は、実施せずに改善点として文章で書いてください。

## 報告内容

この報告は、次サイクルのS（相談）へそのまま引き継がれます。
次の担当者が読んで議論を始められるように、次を簡潔にまとめて回答してください。

- 実際に動作させた内容と、その結果（実行したコマンドや確認手順を含む）
- 見つかった改善点。優先度（高 / 中 / 低）と、そう判断した理由を添える
- チーム作業に対する現状の到達度と、次サイクルで重点を置くべき領域
- 今回のサイクルで残った課題、次サイクルへの申し送り
"""


def main() -> int:
    return sub_SPDCA__common.段を実行(
        "A", "C", プロンプト生成_改善, "sub_SPDCA_action", 要員継続=True, 参照区分=("P", "D"),
        直接実行=True,
    )


if __name__ == "__main__":
    raise SystemExit(main())
